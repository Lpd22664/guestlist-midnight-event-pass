import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as ZK from '@midnight-ntwrk/zkir-v2';
import * as Ledger from '../integration/node_modules/@midnight-ntwrk/ledger-v8/midnight_ledger_wasm_fs.js';
import { LocalContractHarness } from '../contracts/local-harness.mjs';
const here=path.dirname(fileURLToPath(import.meta.url));
const assets=path.resolve(here,'../contracts/generated/event-pass');
const paramsRoot=process.env.MIDNIGHT_PARAMS_DIR ?? '/tmp/midnight-zkir-cache/midnight/zk-params';
const bytes=async(p)=>new Uint8Array(await readFile(p));
const sha=(b)=>createHash('sha256').update(b).digest('hex');
const circuit='issue';
const material={proverKey:await bytes(`${assets}/keys/${circuit}.prover`),verifierKey:await bytes(`${assets}/keys/${circuit}.verifier`),ir:await bytes(`${assets}/zkir/${circuit}.bzkir`)};
const ir=ZK.Zkir.deserialize(material.ir); const k=ir.getK();
console.log(JSON.stringify({stage:'artifacts-loaded',syntheticOnly:true,circuit,zkirK:k,keySha256:{prover:sha(material.proverKey),verifier:sha(material.verifierKey),ir:sha(material.ir)}}));
const kmProvider={lookupKey:async(name)=>{assert.equal(name,circuit);return material;},getParams:async(n)=>{assert.equal(n,k);return bytes(path.join(paramsRoot,`bls_midnight_2p${n}`));}};
const h=new LocalContractHarness();
const result=h.call(circuit,h.commitment());
const d=result.proofData;
const preimage=Ledger.proofDataIntoSerializedPreimage(d.input,d.output,d.publicTranscript,d.privateTranscriptOutputs,circuit);
console.log(JSON.stringify({stage:'synthetic-preimage-created',preimageBytes:preimage.length}));
const checked=await ZK.check(preimage,kmProvider);
console.log(JSON.stringify({stage:'witness-constraint-check-complete',outputs:checked.map(x=>x?.toString()??null)}));
const started=Date.now();
console.log(JSON.stringify({stage:'real-proving-started',concurrency:1}));
const proof=await ZK.prove(preimage,kmProvider,0n);
assert(proof instanceof Uint8Array && proof.length>0);
await mkdir(path.join(here,'evidence'),{recursive:true});
await writeFile(path.join(here,'evidence','synthetic-issue-proof.bin'),proof);
const report={stage:'real-proof-returned',proofBytes:proof.length,proofSha256:sha(proof),elapsedMs:Date.now()-started,syntheticOnly:true,transactionSubmitted:false,networkFinalization:false,separateCryptographicVerification:false};
await writeFile(path.join(here,'evidence','proof-result.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
